    private void btnAplicarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAplicarActionPerformed
        // Pone la oferta al producto o a la categoria elegida con el descuento y los dias escritos
        if (st == null) {
            return;
        }
        double porcentaje;
        int dias;
        try {
            porcentaje = Double.parseDouble(txtDescuento.getText().trim().replace(',', '.'));
            dias = Integer.parseInt(txtDias.getText().trim());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Escribe números válidos en descuento y duración.", "Datos inválidos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int elegido = comboxElegir.getSelectedIndex();
        if (elegido < 0) {
            JOptionPane.showMessageDialog(this, "Elige un producto o una categoría.", "Falta elegir", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String error;
        if (comboxAplicar.getSelectedIndex() == 0) {
            error = st.aplicarOfertaProducto(productosCombo.get(elegido), porcentaje, dias);
        } else {
            error = st.aplicarOfertaCategoria(Categorias.values()[elegido], porcentaje, dias);
        }
        if (error != null) {
            JOptionPane.showMessageDialog(this, error, "No se puede aplicar", JOptionPane.WARNING_MESSAGE);
            return;
        }
        JOptionPane.showMessageDialog(this, "Oferta aplicada a " + comboxElegir.getSelectedItem() + ".");
        txtDescuento.setText("");
        txtDias.setText("");
        actualizarTabla();
    }//GEN-LAST:event_btnAplicarActionPerformed

    private void btnQuitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarActionPerformed
        // Quita la oferta de la fila elegida en la tabla; si no hay fila elegida, la del producto o categoria del combo
        if (st == null) {
            return;
        }
        int fila = tblOfertas.getSelectedRow();
        if (fila >= 0) {
            Producto p = productosEnTabla.get(fila);
            st.quitarOferta(p);
            JOptionPane.showMessageDialog(this, "Oferta de " + p.getNombre() + " quitada.");
        } else if (comboxAplicar.getSelectedIndex() == 0) {
            int elegido = comboxElegir.getSelectedIndex();
            if (elegido < 0) {
                JOptionPane.showMessageDialog(this, "Elige una fila de la tabla o un producto.", "Falta elegir", JOptionPane.WARNING_MESSAGE);
                return;
            }
            Producto p = productosCombo.get(elegido);
            if (!p.tieneOferta()) {
                JOptionPane.showMessageDialog(this, p.getNombre() + " no tiene una oferta vigente.", "Sin oferta", JOptionPane.WARNING_MESSAGE);
                return;
            }
            st.quitarOferta(p);
            JOptionPane.showMessageDialog(this, "Oferta de " + p.getNombre() + " quitada.");
        } else {
            int elegido = comboxElegir.getSelectedIndex();
            if (elegido < 0) {
                return;
            }
            int cantidad = st.quitarOfertaCategoria(Categorias.values()[elegido]);
            if (cantidad == 0) {
                JOptionPane.showMessageDialog(this, "Esa categoría no tiene ofertas vigentes.", "Sin oferta", JOptionPane.WARNING_MESSAGE);
                return;
            }
            JOptionPane.showMessageDialog(this, "Oferta quitada de " + cantidad + " producto(s).");
        }
        actualizarTabla();
    }//GEN-LAST:event_btnQuitarActionPerformed

