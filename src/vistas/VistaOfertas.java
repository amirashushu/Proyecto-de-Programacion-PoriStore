    private void llenarElegir() {
        if (st == null) {
            return;
        }
        productosCombo = new ArrayList<>(st.getProductos());
        ArrayList<String> nombres = new ArrayList<>();
        if (comboxAplicar.getSelectedIndex() == 0) {
            for (Producto p : productosCombo) {
                nombres.add(p.getNombre());
            }
        } else {
            for (Categorias c : Categorias.values()) {
                nombres.add(c.toString());
            }
        }
        comboxElegir.setModel(new DefaultComboBoxModel<>(nombres.toArray(new String[0])));
    }

    //Una fila por cada producto con oferta vigente, tambien los de una categoria completa
    private void actualizarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblOfertas.getModel();
        modelo.setRowCount(0);
        productosEnTabla = st.getProductosConOferta();
        DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd-MM-yyyy");
        for (Producto p : productosEnTabla) {
            modelo.addRow(new Object[]{
                p.getNombre(),
                SistemaTienda.formatoPesos(p.getPrecioBase()),
                SistemaTienda.formatoPesos(p.getPrecio()) + " (-" + (int) p.getOfertaPorcentaje() + "%)",
                p.getOfertaHasta().format(formato)
            });
        }
    }

